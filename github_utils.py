# github_utils.py - Shared GitHub utility functions
import logging
import os
import base64
import httpx

log = logging.getLogger("github_utils")

async def open_reduction_pr(role_arn: str) -> str | None:
    github_token = os.environ.get("GITHUB_TOKEN", "")
    github_repo = os.environ.get("GITHUB_REPO", "")

    if not github_token or not github_repo:
        log.error("GITHUB_TOKEN or GITHUB_REPO not set — cannot open PR")
        return None

    headers = {
        "Authorization": f"Bearer {github_token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }

    safe_arn = (
        role_arn.replace(":", "-")
                .replace("/", "-")
                .replace("_", "-")
                .lower()
    )
    branch_name = f"ace/reduce-{safe_arn}"[:100]

    try:
        async with httpx.AsyncClient(timeout=30) as client:
            # 1. Get default branch SHA
            repo_resp = await client.get(
                f"https://api.github.com/repos/{github_repo}",
                headers=headers,
            )
            repo_resp.raise_for_status()
            default_branch = repo_resp.json()["default_branch"]

            ref_resp = await client.get(
                f"https://api.github.com/repos/{github_repo}/git/ref/heads/{default_branch}",
                headers=headers,
            )
            ref_resp.raise_for_status()
            base_sha = ref_resp.json()["object"]["sha"]

            # 2. Create branch
            branch_resp = await client.post(
                f"https://api.github.com/repos/{github_repo}/git/refs",
                headers=headers,
                json={"ref": f"refs/heads/{branch_name}", "sha": base_sha},
            )
            if branch_resp.status_code not in (201, 422):
                branch_resp.raise_for_status()

            # 3. Get current tree SHA for the commit
            commit_resp = await client.get(
                f"https://api.github.com/repos/{github_repo}/git/commits/{base_sha}",
                headers=headers,
            )
            commit_resp.raise_for_status()
            tree_sha = commit_resp.json()["tree"]["sha"]

            # 4. Create a blob for the reduction plan file
            role_slug = safe_arn.replace("ace-reduce-", "")
            file_content = (
                f"# ACE Reduction Plan\n\n"
                f"**Role ARN:** `{role_arn}`\n\n"
                f"**Status:** Pending least-privilege reduction\n\n"
                f"**Generated by:** ACE Sweeper\n\n"
                f"## Action Required\n\n"
                f"Review and apply the least-privilege policy for this IAM role.\n"
                f"Remove permissions that have not been used in the last 90 days.\n"
            )
            import base64
            blob_resp = await client.post(
                f"https://api.github.com/repos/{github_repo}/git/blobs",
                headers=headers,
                json={
                    "content": base64.b64encode(file_content.encode()).decode(),
                    "encoding": "base64",
                },
            )
            blob_resp.raise_for_status()
            blob_sha = blob_resp.json()["sha"]

            # 5. Create new tree with the reduction plan file
            tree_resp = await client.post(
                f"https://api.github.com/repos/{github_repo}/git/trees",
                headers=headers,
                json={
                    "base_tree": tree_sha,
                    "tree": [{
                        "path": f"ace-reductions/{role_slug}.md",
                        "mode": "100644",
                        "type": "blob",
                        "sha": blob_sha,
                    }],
                },
            )
            tree_resp.raise_for_status()
            new_tree_sha = tree_resp.json()["sha"]

            # 6. Create commit
            new_commit_resp = await client.post(
                f"https://api.github.com/repos/{github_repo}/git/commits",
                headers=headers,
                json={
                    "message": f"ace: reduction plan for {role_arn}",
                    "tree": new_tree_sha,
                    "parents": [base_sha],
                },
            )
            new_commit_resp.raise_for_status()
            new_commit_sha = new_commit_resp.json()["sha"]

            # 7. Update branch to point to new commit
            await client.patch(
                f"https://api.github.com/repos/{github_repo}/git/refs/heads/{branch_name}",
                headers=headers,
                json={"sha": new_commit_sha, "force": True},
            )

            # 8. Open PR
            pr_resp = await client.post(
                f"https://api.github.com/repos/{github_repo}/pulls",
                headers=headers,
                json={
                    "title": f"ACE: Reduce permissions for {role_arn}",
                    "body": (
                        f"Automatically opened by ACE after in-app approval.\n\n"
                        f"**Role ARN:** `{role_arn}`\n"
                        f"**Action:** Reduce to least-privilege based on last-used activity.\n\n"
                        f"Review and merge to complete the remediation."
                    ),
                    "head": branch_name,
                    "base": default_branch,
                },
            )

            if pr_resp.status_code == 422:
                existing = await client.get(
                    f"https://api.github.com/repos/{github_repo}/pulls",
                    headers=headers,
                    params={
                        "head": f"{github_repo.split('/')[0]}:{branch_name}",
                        "state": "open",
                    },
                )
                prs = existing.json()
                return prs[0]["html_url"] if prs else None

            pr_resp.raise_for_status()
            return pr_resp.json()["html_url"]

    except Exception as e:
        log.error(f"open_reduction_pr failed for {role_arn}: {e}", exc_info=True)
        return None